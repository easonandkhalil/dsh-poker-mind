/* Build the DSH client artifact from the shared poker engine and the quick-table UI. */
const fs = require('fs');
const path = require('path');

const root = path.resolve(__dirname, '..');
const engineRoot = path.join(root, 'src', 'engine');
const files = [
  path.join(engineRoot, 'data/charts.js'),
  path.join(engineRoot, 'data/opponents.js'),
  path.join(engineRoot, 'poker/cards.js'),
  path.join(engineRoot, 'poker/evaluator.js'),
  path.join(engineRoot, 'poker/ranges.js'),
  path.join(engineRoot, 'poker/equity.js'),
  path.join(engineRoot, 'poker/range-model.js'),
  path.join(engineRoot, 'poker/game.js'),
  path.join(engineRoot, 'poker/ai.js'),
  path.join(engineRoot, 'poker/coach.js')
];

const engine = files.map((file) => {
  let code = fs.readFileSync(file, 'utf8');
  const before = code;
  code = code.replace(/\}\)\(typeof window !== 'undefined' \? window : globalThis\);\s*$/, '})(PM_ROOT);');
  if (code === before) throw new Error('Unexpected engine tail: ' + file);
  return '\n/* ---- ' + path.basename(file) + ' ---- */\n' + code;
}).join('\n');

if (/typeof window/.test(engine)) throw new Error('Engine still references window');

const ui = fs.readFileSync(path.join(root, 'src/ui.js'), 'utf8');

const output = `/* Generated by src/build-client.cjs. Do not edit by hand. */
window.__ModuleLoader__.load({
  id: 'dsh-poker-mind',
  factory(require) {
    const React = require('react');
    const { useState, useRef, useEffect } = React;
    const h = React.createElement;
    const PM = {};
    const PM_ROOT = { PM };
${engine}
${ui}
    return {
      inject: ['slots'],
      apply(ctx) {
        ctx.slots.inject('conversation.composer.dock', () => ctx.slots.register({
          name: 'conversation.composer.dock',
          id: 'poker-mind-dsh.launch',
          order: 8
        }, PokerLaunchButton));
        ctx.slots.inject('shell.overlay', () => ctx.slots.register({
          name: 'shell.overlay',
          id: 'poker-mind-dsh.table'
        }, PokerTable));
      }
    };
  }
});
`;

fs.writeFileSync(path.join(root, 'client.js'), output, 'utf8');
console.log('wrote client.js', Buffer.byteLength(output), 'bytes');
